function P = motor_params()
%MOTOR_PARAMS  直流有刷伺服电机模型参数（三环伺服控制系统公用）
%
% 选取一款典型 24V 直流有刷伺服电机（减速比 1:1 直接驱动），
% 参数取值依据见设计报告"系统建模"一节：
%   - 额定电压 24V，电枢回路电阻/电感由绕组工艺决定
%   - SI 单位制下转矩系数 Km 与反电动势系数 Kb 数值相等 (Kt = Ke)
%   - Je 为转子 + 负载折算到电机轴的总转动惯量（减速比 1:1）

P.Un  = 24;         % 额定电压 (V)
P.Ra  = 1.5;        % 电枢电阻 (Ohm)
P.La  = 2.5e-3;     % 电枢电感 (H)      -> 电磁时间常数 La/Ra = 1.67 ms
P.Km  = 0.05;       % 转矩系数 (N*m/A)
P.Kb  = 0.05;       % 反电动势系数 (V*s/rad)
P.Je  = 2.0e-4;     % 折算总转动惯量 (kg*m^2) -> 机电时间常数 Je*Ra/(Km*Kb) = 120 ms

% 驱动电路 (PWM + H 桥) 等效模型
P.Kpwm = 1.0;       % PWM驱动器小信号等效增益：控制电压 0~24V 对应占空比 0~100%
P.Umax = 24;        % 母线电压 / 电压饱和限幅 (V)
P.Imax = 10;        % 电流环限幅 (A)

% 系统参数（依据 PPT"系统参数"页）
P.Ts       = 1e-3;              % 系统采样时间 1 ms
P.enc_bits = 16;                % 绝对式编码器 16 位
P.enc_res  = 360/2^P.enc_bits;  % 编码器分辨率 0.0055 deg
P.gyro_max = 1000*pi/180;       % 陀螺仪量程 ±1000 deg/s (rad/s)

% 反馈噪声设定（依据 PPT 噪声特性）
P.noise_i_NP = 2e-6;    % 电流环噪声: 功率谱密度 ~ 1/f
P.noise_v_NP = 6e-7;    % 速度环噪声: 30~100 Hz 频段
P.noise_p_NP = 3e-12;   % 位置环噪声: 20~60 Hz 频段

% 三环控制器参数（整定依据见各任务脚本注释与报告）
% 电流环 PI：零点对消电磁极点 Ra/La，穿越频率约 300 rad/s
P.Kpi_i = 0.75;  P.Ti_i = P.La/P.Ra;      % 电流环: Kpi*(1+1/(Ti*s))
% 速度环 PI：穿越频率约 50 rad/s，相角裕度约 76 deg
P.Kpi_v = 0.20;  P.Ti_v = 0.08;           % 速度环: Kpv*(1+1/(Tv*s))
% 位置环 PID（任务四手动整定初值，任务五由 PSO 优化）
P.Kpp = 10;  P.Kpi = 0;  P.Kpd = 0;       % 位置环 PID 增益
P.Vref_max = 17;   % 速度给定限幅 (rad/s)，受陀螺仪量程 ±1000 deg/s 约束
end
